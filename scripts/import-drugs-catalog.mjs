#!/usr/bin/env node
/**
 * Import the official Egyptian drug catalogue into Supabase.
 *
 *   node scripts/import-drugs-catalog.mjs                    # upsert everything
 *   node scripts/import-drugs-catalog.mjs --batch 500
 *   node scripts/import-drugs-catalog.mjs --csv              # read the CSV instead
 *   node scripts/import-drugs-catalog.mjs --dry-run
 *
 * Requires `supabase/migrations/003_drugs_catalog.sql` to be applied first, and
 * SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY in the environment (they are also
 * read from .env.local so `npm run import:drugs` works without extra tooling).
 *
 * The catalogue JSON is generated by `python extract_drugs.py`.
 */

import { createClient } from "@supabase/supabase-js";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const ROOT = path.resolve(import.meta.dirname, "..");
const JSON_PATH = path.join(ROOT, "supabase", "seed", "drugs_catalog.json");
const BATCH = 500;

// ---------------------------------------------------------------------------
// args
// ---------------------------------------------------------------------------
function parseArgs(argv) {
  const args = { batch: BATCH, dryRun: false, csv: false, jsonPath: JSON_PATH, prune: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--dry-run") args.dryRun = true;
    else if (arg === "--csv") args.csv = true;
    else if (arg === "--prune") args.prune = true;
    else if (arg === "--batch") args.batch = Number(argv[++i]);
    else if (arg === "--json") args.jsonPath = path.resolve(argv[++i]);
    else if (arg === "--help" || arg === "-h") {
      console.log("usage: node scripts/import-drugs-catalog.mjs [--batch N] [--csv] [--dry-run] [--prune]");
      process.exit(0);
    } else {
      console.error(`unknown argument: ${arg}`);
      process.exit(1);
    }
  }
  if (!Number.isFinite(args.batch) || args.batch < 1 || args.batch > 2000) args.batch = BATCH;
  return args;
}

// ---------------------------------------------------------------------------
// env
// ---------------------------------------------------------------------------
function readEnvFile(file) {
  if (!fs.existsSync(file)) return {};
  const out = {};
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const match = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/.exec(line);
    if (!match) continue;
    let value = match[2].trim();
    if (value.startsWith('"') && value.endsWith('"')) value = value.slice(1, -1);
    if (value.startsWith("'") && value.endsWith("'")) value = value.slice(1, -1);
    out[match[1]] = value;
  }
  return out;
}

function supabaseConfig() {
  const fileEnv = {
    ...readEnvFile(path.join(ROOT, ".env")),
    ...readEnvFile(path.join(ROOT, ".env.local")),
  };
  const url =
    process.env.SUPABASE_URL ??
    process.env.NEXT_PUBLIC_SUPABASE_URL ??
    fileEnv.SUPABASE_URL ??
    fileEnv.NEXT_PUBLIC_SUPABASE_URL;
  const key =
    process.env.SUPABASE_SERVICE_ROLE_KEY ??
    process.env.SUPABASE_SECRET_KEY ??
    fileEnv.SUPABASE_SERVICE_ROLE_KEY ??
    fileEnv.SUPABASE_SECRET_KEY;

  if (!url || !key) {
    console.error(
      [
        "Missing Supabase credentials.",
        "Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY (or NEXT_PUBLIC_SUPABASE_URL +",
        "SUPABASE_SERVICE_ROLE_KEY) in the environment or in .env.local.",
      ].join("\n"),
    );
    process.exit(1);
  }
  return { url, key };
}

// ---------------------------------------------------------------------------
// data
// ---------------------------------------------------------------------------
const DOSAGE_FORMS = new Set(["TABLETS", "SYRUP", "INJECTION", "CREAM", "DROPS", "OTHER"]);

function toRow(drug) {
  return {
    source_key: drug.id,
    name_en: drug.name_en ?? "",
    name_ar: drug.name_ar ?? "",
    active_ingredient: drug.active_ingredient ?? "",
    company: drug.company ?? "",
    dosage_form: DOSAGE_FORMS.has(drug.dosage_form) ? drug.dosage_form : "OTHER",
    pack_size: drug.pack_size ?? null,
    category: drug.category ?? "",
    public_price_egp: Number(drug.public_price_egp) || 0,
    barcode: drug.barcode ?? null,
  };
}

/** Minimal RFC-4180 CSV reader — the seed CSV is machine generated, no quoting surprises. */
function readCsv(file) {
  const text = fs.readFileSync(file, "utf8").replace(/^\uFEFF/, "");
  const lines = text.split(/\r?\n/).filter((line) => line.length > 0);
  const header = lines.shift().split(",");
  return lines.map((line) => {
    const cells = [];
    let cell = "";
    let quoted = false;
    for (let i = 0; i < line.length; i += 1) {
      const ch = line[i];
      if (quoted) {
        if (ch === '"' && line[i + 1] === '"') {
          cell += '"';
          i += 1;
        } else if (ch === '"') quoted = false;
        else cell += ch;
      } else if (ch === '"') quoted = true;
      else if (ch === ",") {
        cells.push(cell);
        cell = "";
      } else cell += ch;
    }
    cells.push(cell);
    const row = {};
    header.forEach((name, index) => {
      row[name] = cells[index] ?? "";
    });
    return toRow({
      ...row,
      pack_size: row.pack_size ? Number(row.pack_size) : null,
      barcode: row.barcode || null,
      public_price_egp: Number(row.public_price_egp) || 0,
    });
  });
}

function readRows(args) {
  if (args.csv) {
    const csvPath = path.join(ROOT, "supabase", "seed", "drugs_catalog.csv");
    if (!fs.existsSync(csvPath)) throw new Error(`missing ${csvPath} — run \`python extract_drugs.py\`.`);
    return readCsv(csvPath);
  }

  if (!fs.existsSync(args.jsonPath)) {
    throw new Error(`missing ${args.jsonPath} — run \`python extract_drugs.py\`.`);
  }
  const payload = JSON.parse(fs.readFileSync(args.jsonPath, "utf8"));
  const drugs = Array.isArray(payload.drugs) ? payload.drugs : [];
  return drugs.map(toRow);
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------
async function main() {
  const args = parseArgs(process.argv.slice(2));
  const rows = readRows(args);

  const missingKey = rows.filter((row) => !row.source_key);
  const cleaned = rows.filter((row) => row.source_key);

  console.log(`catalogue rows : ${rows.length.toLocaleString("en-US")}`);
  if (missingKey.length) console.log(`  skipped      : ${missingKey.length} (no source_key)`);
  console.log(`  priced > 0   : ${cleaned.filter((r) => r.public_price_egp > 0).length.toLocaleString("en-US")}`);
  console.log(`  with Arabic  : ${cleaned.filter((r) => r.name_ar).length.toLocaleString("en-US")}`);

  if (args.dryRun) {
    console.log("\n--dry-run: nothing was sent to Supabase.");
    console.log(JSON.stringify(cleaned[0], null, 2));
    return;
  }

  const { url, key } = supabaseConfig();
  const supabase = createClient(url, key, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  let done = 0;
  const started = Date.now();

  for (let offset = 0; offset < cleaned.length; offset += args.batch) {
    const batch = cleaned.slice(offset, offset + args.batch);
    const { error } = await supabase
      .from("drugs_catalog")
      .upsert(batch, { onConflict: "source_key", ignoreDuplicates: false });

    if (error) {
      console.error(`\n✗ batch at row ${offset} failed: ${error.message}`);
      if (error.hint) console.error(`  hint: ${error.hint}`);
      process.exit(1);
    }

    done += batch.length;
    const pct = ((done / cleaned.length) * 100).toFixed(1);
    process.stdout.write(`\r  upserted ${done.toLocaleString("en-US")} / ${cleaned.length.toLocaleString("en-US")} (${pct}%)`);
  }

  process.stdout.write("\n");

  if (args.prune) {
    // Remove catalogue rows whose source file no longer contains them.
    const keys = new Set(cleaned.map((row) => row.source_key));
    const { data, error } = await supabase.from("drugs_catalog").select("source_key");
    if (error) {
      console.error(`✗ prune query failed: ${error.message}`);
      process.exit(1);
    }
    const stale = (data ?? []).map((row) => row.source_key).filter((sourceKey) => !keys.has(sourceKey));
    if (stale.length) {
      for (let offset = 0; offset < stale.length; offset += args.batch) {
        const slice = stale.slice(offset, offset + args.batch);
        const { error: deleteError } = await supabase.from("drugs_catalog").delete().in("source_key", slice);
        if (deleteError) {
          console.error(`✗ prune failed: ${deleteError.message}`);
          process.exit(1);
        }
      }
    }
    console.log(`pruned ${stale.length.toLocaleString("en-US")} stale rows`);
  }

  const seconds = ((Date.now() - started) / 1000).toFixed(1);
  console.log(`✓ imported ${done.toLocaleString("en-US")} catalogue rows in ${seconds}s`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
